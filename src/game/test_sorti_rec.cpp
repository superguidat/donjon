bool		test_sorti_rec(t_rec		&rec,
			       int32_t		step,
			       t_path		&origin)
{
  return (rec.max_step != 0
	  && step == rec.max_step)
    ||(origin.pos.x == rec.destination.x
       && origin.pos.y == rec.destination.y);
}

