#include		"donjon_master.hh"

void			test_dist(t_path		tmp,
				  t_path		&pat,
				  t_map			*map)
{
  if (tmp.dist < map->dist)
    {
      map->best_pos.x = tmp.pos.x;
      map->best_pos.y = tmp.pos.y;
      map->dist = tmp.dist;
      pat = tmp;
    }
}
