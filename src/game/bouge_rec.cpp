#include	"donjon_master.hh"

void		bouge_rec(int32_t				t,
			  uint8_t				*pos,
			  t_bunny_position			&origin)
{
  if (pos[t-1] == 0)
    origin.x ++;
  else if (pos[t-1] == 1)
    origin.y ++;
  else if (pos[t-1] == 2)
    origin.x --;
  else if (pos[t-1] == 3)
    origin.y --;
}
