#include	"donjon_master.hh"

void		init_pos_move(t_bunny_position		&pos,
			      t_move			&mv)
{
  int		dir = mv.pnj->getDir();

  if (dir == 0)
    pos.x ++;
  else if (dir == 1)
    pos.y ++;
  else if (dir == 2)
    pos.x --;
  else if (dir == 3)
    pos.y --;
}
