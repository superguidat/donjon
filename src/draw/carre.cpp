#include		"donjon_master.hh"

void			set_carre_pix(t_bunny_pixelarray	*map2,
				      ef::Unit		&pnj,
				      uint32_t		i)
{
  int16_t		x;
  int16_t		y;
  int16_t		r;

  x = pnj.getX();
  y = pnj.getY();
  r = pnj.getR();

  for (int16_t y2 = y - r; y2 < y + r; y2 ++)
    {
      for (int16_t x2 = x - r; x2 < x + r; x2 ++)
	{
	  ((uint32_t *)(map2->pixels))[y2 * map2->clipable.buffer.width + x2] = i;
	}
    }
}
